function forecastStatus(score) {
  if (score >= 90) return { status: 'excellent', label: '가장 좋은 날' };
  if (score >= 84) return { status: 'good', label: '추천' };
  if (score >= 76) return { status: 'fair', label: '조건 확인' };
  return { status: 'caution', label: '실내 대안' };
}

